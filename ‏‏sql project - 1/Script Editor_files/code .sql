CREATE TABLE "User" (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(50) NOT NULL UNIQUE,
    email         VARCHAR2(100) NOT NULL UNIQUE,
    password_hash VARCHAR2(128) NOT NULL,
    salt          VARCHAR2(32) NOT NULL,
    full_name     VARCHAR2(100),
    is_active     CHAR(1) DEFAULT 'Y' CHECK (is_active IN ('Y','N')),
    created_at    DATE DEFAULT SYSDATE,
    last_login    DATE
);

CREATE TABLE ROLES (
    role_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   VARCHAR2(50) NOT NULL UNIQUE,
    description VARCHAR2(200),
    created_at  DATE DEFAULT SYSDATE
);

CREATE TABLE PERMISSIONS (
    permission_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code VARCHAR2(50) NOT NULL UNIQUE,
    description     VARCHAR2(200),
    resource_name   VARCHAR2(50), 
    action          VARCHAR2(20)
);

CREATE TABLE USER_ROLES (
    user_id     NUMBER NOT NULL,
    role_id     NUMBER NOT NULL,
    assigned_at DATE DEFAULT SYSDATE,
    assigned_by NUMBER,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES "User"(user_id),
    CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES ROLES(role_id),
    CONSTRAINT fk_ur_assigned_by FOREIGN KEY (assigned_by) REFERENCES "User"(user_id)
);

CREATE TABLE ROLE_PERMISSIONS (
    role_id       NUMBER NOT NULL,
    permission_id NUMBER NOT NULL,
    granted_at    DATE DEFAULT SYSDATE,
    CONSTRAINT pk_role_perms PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES ROLES(role_id),
    CONSTRAINT fk_rp_perm FOREIGN KEY (permission_id) REFERENCES PERMISSIONS(permission_id)
);

CREATE TABLE POLICIES (
    policy_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name     VARCHAR2(100) NOT NULL,
    condition_type  VARCHAR2(50),
    condition_value VARCHAR2(200),
    is_active       CHAR(1) DEFAULT 'Y' CHECK (is_active IN ('Y','N')),
    created_at      DATE DEFAULT SYSDATE
);

CREATE TABLE ACCESS_LOGS (
    log_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER,
    action     VARCHAR2(50),
    status     VARCHAR2(20),
    ip_address VARCHAR2(45),
    user_agent VARCHAR2(200),
    log_time   DATE DEFAULT SYSDATE,
    details    VARCHAR2(500),
    CONSTRAINT fk_log_user FOREIGN KEY (user_id) REFERENCES "User"(user_id)
);

CREATE TABLE MFA_TOKENS (
    token_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER NOT NULL,
    token_code VARCHAR2(10) NOT NULL,
    expires_at DATE NOT NULL,
    is_used    CHAR(1) DEFAULT 'N' CHECK (is_used IN ('Y','N')),
    created_at DATE DEFAULT SYSDATE,
    CONSTRAINT fk_mfa_user FOREIGN KEY (user_id) REFERENCES "User"(user_id)
);

CREATE TABLE SESSIONS (
    session_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       NUMBER NOT NULL,
    session_token VARCHAR2(128) NOT NULL,
    ip_address    VARCHAR2(45),
    login_time    DATE DEFAULT SYSDATE,
    logout_time   DATE,
    is_active     CHAR(1) DEFAULT 'Y' CHECK (is_active IN ('Y','N')),
    CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES "User"(user_id)
);

CREATE TABLE AUDIT_TRAIL (
    audit_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER,
    table_name VARCHAR2(50),
    action     VARCHAR2(20),
    old_value  VARCHAR2(500),
    new_value  VARCHAR2(500),
    changed_at DATE DEFAULT SYSDATE,
    ip_address VARCHAR2(45),
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES "User"(user_id)
);

CREATE OR REPLACE TRIGGER trg_hash_password
BEFORE INSERT OR UPDATE OF password_hash ON "User"
FOR EACH ROW
BEGIN
    IF :NEW.password_hash IS NOT NULL AND LENGTH(:NEW.password_hash) < 64 THEN
        :NEW.salt := TO_CHAR(SYSTIMESTAMP, 'YYYYMMDDHH24MISSFF');
        :NEW.password_hash := TO_CHAR(
            DBMS_UTILITY.GET_HASH_VALUE(:NEW.password_hash || :NEW.salt, 1, 1073741823), 
            'FMXXXXXXXX'
        ) || TO_CHAR(
            DBMS_UTILITY.GET_HASH_VALUE(:NEW.salt || :NEW.password_hash, 1, 1073741823), 
            'FMXXXXXXXX'
        ) || TO_CHAR(
            DBMS_UTILITY.GET_HASH_VALUE(:NEW.password_hash || 'X' || :NEW.salt, 1, 1073741823), 
            'FMXXXXXXXX'
        ) || TO_CHAR(
            DBMS_UTILITY.GET_HASH_VALUE(:NEW.salt || 'Y' || :NEW.password_hash, 1, 1073741823), 
            'FMXXXXXXXX'
        );
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_audit_user
AFTER INSERT ON "User"
FOR EACH ROW
BEGIN
    INSERT INTO AUDIT_TRAIL (user_id, table_name, action, new_value, ip_address)
    VALUES (:NEW.user_id, 'User', 'INSERT', 'New user: ' || :NEW.username, SYS_CONTEXT('USERENV', 'IP_ADDRESS'));
END;
/

CREATE OR REPLACE VIEW V_USER_ACCESS AS
SELECT 
    u.user_id,
    u.username,
    u.full_name,
    r.role_name,
    p.permission_code,
    p.resource_name, 
    p.action
FROM "User" u
JOIN USER_ROLES ur ON u.user_id = ur.user_id
JOIN ROLES r ON ur.role_id = r.role_id
JOIN ROLE_PERMISSIONS rp ON r.role_id = rp.role_id
JOIN PERMISSIONS p ON rp.permission_id = p.permission_id;

